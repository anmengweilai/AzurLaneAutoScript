CONFIG_LOCKS: Dict[str, threading.RLock] = {}
CONFIG_LOCKS_GUARD = threading.Lock()


def json_safe(value: Any) -> Any:
    """Convert Python objects generated by config migration to JSON values."""
    if isinstance(value, datetime.datetime):
        return value.strftime("%Y-%m-%d %H:%M:%S")
    if isinstance(value, datetime.date):
        return value.isoformat()
    if isinstance(value, dict):
        return {str(key): json_safe(item) for key, item in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [json_safe(item) for item in value]
    if isinstance(value, bytes):
        return value.decode("utf-8", errors="replace")
    return value


def config_lock(name: str) -> threading.RLock:
    with CONFIG_LOCKS_GUARD:
        return CONFIG_LOCKS.setdefault(name, threading.RLock())


class ConfigControl:
    def args(self, mod_name: str = "alas") -> Dict[str, Any]:
        try:
            return read_file(filepath_args("args", mod_name))
        except (FileNotFoundError, OSError):
            raise NotFound(f"Config schema not found for mod: {mod_name}", code="SCHEMA_NOT_FOUND")

    def menu(self, mod_name: str = "alas") -> Dict[str, Any]:
        try:
            return read_file(filepath_args("menu", mod_name))
        except (FileNotFoundError, OSError):
            raise NotFound(f"Config menu not found for mod: {mod_name}", code="MENU_NOT_FOUND")

    def locale(self, locale: str) -> Dict[str, Any]:
        from module.config.utils import LANGUAGES

        if locale not in LANGUAGES:
            raise NotFound(f"Language not supported: {locale}", code="LANGUAGE_NOT_FOUND")
        return read_file(filepath_i18n(locale))

    def read(self, name: str) -> Dict[str, Any]:
        self.assert_exists(name)
        with config_lock(name):
            return State.config_updater.read_file(name)

    def read_json(self, name: str) -> Dict[str, Any]:
        return json_safe(self.read(name))

    def assert_exists(self, name: str) -> None:
        from module.config.utils import alas_instance

        if name not in alas_instance():
            raise NotFound(f"Instance not found: {name}", code="INSTANCE_NOT_FOUND")

    def _schema_item(self, args: Dict[str, Any], path: str) -> Dict[str, Any]:
        value = deep_get(args, path)
        if not isinstance(value, dict) or "type" not in value:
            raise InvalidArgument(f"Unknown config path: {path}", details={"path": path})
        display = value.get("display")
        if display in ("readonly", "hide", "disabled"):
            raise InvalidArgument(f"Config path is not editable: {path}", details={"path": path})
        return value

    @staticmethod
    def _datetime(value: Any) -> Optional[datetime.datetime]:
        if isinstance(value, datetime.datetime):
            return value
        if isinstance(value, str):
            try:
                return datetime.datetime.fromisoformat(value)
            except ValueError:
                return None
        return None

    def _parse_value(self, path: str, value: Any, schema: Dict[str, Any]) -> Any:
        field_type = schema.get("type")
        if field_type == "checkbox":
            return bool(value)

        if value is None or (isinstance(value, str) and not value.strip()):
            return schema.get("value")

        if field_type == "select":
            options = schema.get("option", [])
            if options and value not in options:
                raise InvalidArgument(f"Value is not an allowed option", details={"path": path, "value": value})
            return value

        if schema.get("valuetype") == "str":
            return str(value)

        if field_type == "datetime":
            parsed = self._datetime(value)
            if parsed is None:
                raise InvalidArgument("Value must be YYYY-MM-DD HH:mm:ss", details={"path": path, "value": value})
            return parsed.strftime("%Y-%m-%d %H:%M:%S")

        if isinstance(value, (int, float, bool)):
            return value

        text = str(value)
        if text.lower() in ("true", "false"):
            return text.lower() == "true"
        if "." in text:
            try:
                return float(text)
            except ValueError:
                pass
        else:
            try:
                return int(text)
            except ValueError:
                pass
        return text

    def validate(
        self,
        name: str,
        args: Dict[str, Any],
        changes: Iterable[Tuple[str, Any]],
    ) -> Tuple[Dict[str, Any], List[str], List[str]]:
        config = self.read(name)
        accepted: Dict[str, Any] = {}
        warnings: List[str] = []

        cleaned: Dict[str, Any] = {}
        for path, raw_value in changes:
            if not isinstance(path, str) or not path:
                raise InvalidArgument("Each change requires a non-empty path")
            schema = self._schema_item(args, path)
            value = self._parse_value(path, raw_value, schema)
            validate = schema.get("validate")
            if validate and not len(str(value)):
                value = schema.get("value")
            elif validate and not re_fullmatch(validate, value):
                raise InvalidArgument(
                    "Value does not match validation rule",
                    details={"path": path, "value": value, "validate": validate},
                )
            cleaned[path] = value

        for path, value in cleaned.items():
            deep_set(config, path, value)
            accepted[path] = value
            for derived_path, derived_value in State.config_updater.save_callback(path, value):
                deep_set(config, derived_path, derived_value)
                accepted[derived_path] = derived_value

        # Mirror AlasGUI: clear far-future generated time fields when the file is saved.
        now = datetime.datetime.now()
        for path, value in list(deep_iter(config, depth=3)):
            key = ".".join(path)
            if key in accepted or key.endswith("un") or isinstance(value, bool):
                continue
            parsed = self._datetime(value)
            if parsed is not None and (parsed - now).days >= 31:
                deep_set(config, path, "")
                warnings.append(f"Cleared far-future time field: {key}")

        return {"config": config, "accepted": accepted, "warnings": warnings}, list(accepted), warnings

    def patch(
        self,
        name: str,
        changes: List[Dict[str, Any]],
        *,
        dry_run: bool = False,
    ) -> Dict[str, Any]:
        from module.submodule.utils import get_config_mod

        self.assert_exists(name)
        args = self.args(get_config_mod(name))
        with config_lock(name):
            current = self.read(name)
            pairs = [(str(item.get("path", "")), item.get("value")) for item in changes]
            result, accepted, warnings = self.validate(name, args, pairs)
            if dry_run:
                return {
                    "valid": True,
                    "accepted": json_safe(accepted),
                    "derived_changes": [key for key in accepted if key not in {p for p, _ in pairs}],
                    "warnings": warnings,
                    "apply_hint": "dry_run",
                }

            changed = {
                path: value
                for path, value in accepted.items()
                if deep_get(current, path) != value
            }
            if changed:
                State.config_updater.write_file(name, result["config"], get_config_mod(name))
                logger.info(f"Control API saved config [{name}]: {changed}")
            return {
                "valid": True,
                "accepted": json_safe(accepted),
                "derived_changes": [key for key in accepted if key not in changed],
                "warnings": warnings,
                "revision": self.revision(name),
                "apply_hint": self.apply_hint(name, list(changed), args),
            }

    def revision(self, name: str) -> str:
        import hashlib
        import json

        data = self.read(name)
        canonical = json.dumps(data, ensure_ascii=False, sort_keys=True, separators=(",", ":"), default=str)
        return "sha256:" + hashlib.sha256(canonical.encode("utf-8")).hexdigest()

    def apply_hint(self, name: str, paths: List[str], args: Dict[str, Any]) -> str:
        if not paths:
            return "none"
        from module.webui.process_manager import ProcessManager

        manager = ProcessManager.get_manager(name)
        if not manager.alive:
            return "next_start"
        return "running_reload"

    def templates(self) -> List[str]:
        from module.config.utils import alas_template

        return alas_template()

    def create(self, name: str, copy_from: str) -> Dict[str, Any]:
        from module.config.utils import alas_instance
        from module.submodule.submodule import load_config
        from module.submodule.utils import get_config_mod

        self._validate_new_name(name)
        if copy_from not in set(self.templates() + alas_instance()):
            raise NotFound(f"Copy source not found: {copy_from}", code="COPY_SOURCE_NOT_FOUND")
        data = load_config(copy_from).read_file(copy_from)
        State.config_updater.write_file(name, data, get_config_mod(copy_from))
        return {"name": name, "mod": get_config_mod(name)}

    def import_config(self, filename: str, content: str) -> Dict[str, Any]:
        import json

        try:
            data = json.loads(content)
        except (TypeError, json.JSONDecodeError) as error:
            raise InvalidArgument("Import file must be valid JSON", details={"error": str(error)})
        parts = filename.split(".")
        if len(parts) == 2:
            config_name, mod_name = parts[0], "alas"
        elif len(parts) == 3:
            config_name, mod_name = parts[0], parts[1]
        else:
            raise InvalidArgument("Filename must be <name>.json or <name>.<mod>.json")
        if IS_ON_PHONE_CLOUD:
            config_name = mod_name = "alas"
        self._validate_import_name(config_name)
        State.config_updater.write_file(config_name, data, mod_name)
        return {"name": config_name, "mod": mod_name}

    def export_filename(self, name: str) -> str:
        mod_name = get_config_mod(name)
        return f"{name}.json" if mod_name == "alas" else f"{name}.{mod_name}.json"

    def export_path(self, name: str):
        self.assert_exists(name)
        return filepath_config(name, get_config_mod(name))

    def export(self, name: str) -> Dict[str, Any]:
        self.assert_exists(name)
        return {
            "filename": self.export_filename(name),
            "content": json_safe(self.read(name)),
        }

    def _validate_new_name(self, name: str) -> None:
        from module.config.utils import alas_instance

        self._validate_import_name(name)
        if name in alas_instance():
            raise Conflict("Config name already exists", code="CONFIG_NAME_EXISTS")

    def _validate_import_name(self, name: str) -> None:
        if not name or len(name) > 64:
            raise InvalidArgument("Name must contain 1-64 characters")
        if set(name) & set(".\\/:*?\"'<>|"):
            raise InvalidArgument("Name contains invalid characters")
        if name.lower().startswith("template"):
            raise InvalidArgument("Name may not start with template")
